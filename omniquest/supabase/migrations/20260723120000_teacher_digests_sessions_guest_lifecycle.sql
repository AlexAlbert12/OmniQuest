create or replace function public.register_user_session(p_device_id text,p_device_name text,p_platform text,p_user_agent text default null,p_ip_hash text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid:=auth.uid(); v_id uuid; v_new boolean:=false; v_revoked timestamptz;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  select id,revoked_at into v_id,v_revoked from public.user_sessions where user_id=v_user and device_id=p_device_id;
  if v_id is null then
    v_new:=true;
    insert into public.user_sessions(user_id,device_id,device_name,platform,user_agent,ip_hash,new_device_notified_at)
    values(v_user,left(p_device_id,200),left(p_device_name,120),left(p_platform,30),left(p_user_agent,500),p_ip_hash,now()) returning id into v_id;
    perform public.create_notification(
      v_user, case when exists(select 1 from public.profiles where id=v_user and role_id='teacher') then 'teacher' else 'student' end,
      'announcement', 'Nuevo inicio de sesión',
      format('Se ha iniciado sesión desde %s (%s).',left(p_device_name,120),left(p_platform,30)),
      'shield-checkmark-outline', '#F6A64A', null, 'user_sessions', v_id::text,
      jsonb_build_object('session_id',v_id,'device_name',p_device_name,'platform',p_platform),
      'new-device:'||v_user::text||':'||left(p_device_id,200)
    );
  else
    update public.user_sessions set device_name=left(p_device_name,120),platform=left(p_platform,30),user_agent=left(p_user_agent,500),ip_hash=coalesce(p_ip_hash,ip_hash),last_seen_at=now(),updated_at=now() where id=v_id;
  end if;
  return jsonb_build_object('session_id',v_id,'is_new_device',v_new,'revoked',v_revoked is not null);
end $$;

create or replace function public.revoke_user_session(p_session_id uuid)
returns void language plpgsql security definer set search_path=public as $$
begin
  update public.user_sessions set revoked_at=now(),revoked_by=auth.uid(),updated_at=now()
  where id=p_session_id and user_id=auth.uid();
  if not found then raise exception 'Session not found'; end if;
end $$;

create or replace function public.revoke_other_user_sessions(p_current_device_id text)
returns integer language plpgsql security definer set search_path=public as $$
declare v_count integer;
begin
  update public.user_sessions set revoked_at=now(),revoked_by=auth.uid(),updated_at=now()
  where user_id=auth.uid() and device_id<>p_current_device_id and revoked_at is null;
  get diagnostics v_count=row_count; return v_count;
end $$;

