create or replace function public.prepare_guest_profile()
returns trigger language plpgsql set search_path=public as $$
begin
  if new.role_id='guest' and new.expires_at is null then new.expires_at:=now()+interval '30 days'; end if;
  if old.role_id='guest' and new.role_id='student' then new.converted_at:=now(); new.expires_at:=null; end if;
  return new;
end $$;
drop trigger if exists prepare_guest_profile_trigger on public.profiles;
create trigger prepare_guest_profile_trigger before insert or update on public.profiles for each row execute function public.prepare_guest_profile();

create or replace function public.convert_current_guest_to_student(p_alias text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid:=auth.uid();
begin
  update public.profiles set role_id='student',alias=coalesce(nullif(trim(p_alias),''),alias),converted_at=now(),expires_at=null,active=true
  where id=v_user and role_id='guest' and coalesce(expires_at,now()+interval '1 day')>now();
  if not found then raise exception 'Active guest profile required'; end if;
  return jsonb_build_object('converted',true,'user_id',v_user);
end $$;
grant execute on function public.convert_current_guest_to_student(text) to authenticated;

create or replace function public.cleanup_expired_guests(p_limit integer default 200)
returns integer language plpgsql security definer set search_path=public as $$
declare v_count integer;
begin
  with expired as (
    select id from public.profiles where role_id='guest' and converted_at is null and expires_at<=now()
    order by expires_at for update skip locked limit greatest(1,least(p_limit,1000))
  )
  update public.profiles p set active=false,alias='Invitado caducado',points=0
  from expired e where p.id=e.id;
  get diagnostics v_count=row_count;
  delete from public.enrollments e using public.profiles p where e.student_id=p.id and p.role_id='guest' and p.active=false and p.expires_at<=now();
  return v_count;
end $$;
revoke all on function public.cleanup_expired_guests(integer) from public,anon,authenticated;
grant execute on function public.cleanup_expired_guests(integer) to service_role;

