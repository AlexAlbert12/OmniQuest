create or replace function public.invoke_teacher_digest_processor()
returns void language plpgsql security definer set search_path=public,extensions as $$
declare v_url text; v_secret text;
begin
  select decrypted_secret into v_url from vault.decrypted_secrets where name='project_url' limit 1;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name='digest_queue_secret' limit 1;
  if nullif(trim(v_url),'') is null or nullif(trim(v_secret),'') is null then return; end if;
  perform net.http_post(
    url := rtrim(v_url,'/') || '/functions/v1/process-teacher-digests',
    headers := jsonb_build_object('Content-Type','application/json','x-cron-secret',v_secret),
    body := jsonb_build_object('source','pg_cron'),
    timeout_milliseconds := 15000
  );
end $$;
revoke all on function public.invoke_teacher_digest_processor() from public,anon,authenticated;
grant execute on function public.invoke_teacher_digest_processor() to service_role;

do $$ begin
  perform cron.unschedule(jobid) from cron.job where jobname='omniquest-teacher-digest-worker';
exception when undefined_table then null; end $$;
select cron.schedule('omniquest-teacher-digest-worker','*/10 * * * *',$$select public.invoke_teacher_digest_processor();$$);

create or replace function public.get_admin_dashboard_metrics()
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_total_profiles integer:=0; v_teachers_count integer:=0; v_students_count integer:=0;
  v_subjects_count integer:=0; v_classrooms_count integer:=0; v_enrollments_count integer:=0;
  v_active_courses integer:=0; v_archived_courses integer:=0; v_active_classrooms integer:=0;
  v_inactive_users integer:=0; v_courses_without_classrooms integer:=0;
  v_students_without_activity integer:=0; v_classrooms_without_code integer:=0;
begin
  if not public.is_admin() then raise exception 'No autorizado.'; end if;
  select count(*)::integer,
    count(*) filter(where role_id='teacher')::integer,
    count(*) filter(where role_id in('student','guest'))::integer,
    count(*) filter(where active=false)::integer
  into v_total_profiles,v_teachers_count,v_students_count,v_inactive_users
  from public.profiles p
  where not (p.role_id='guest' and p.converted_at is null and p.expires_at<=now());
  select count(*)::integer,count(*) filter(where coalesce(active,true) and not coalesce(is_archived,false))::integer,count(*) filter(where coalesce(is_archived,false))::integer
  into v_subjects_count,v_active_courses,v_archived_courses from public.subjects;
  select count(*)::integer,count(*) filter(where coalesce(active,true))::integer,count(*) filter(where nullif(trim(coalesce(code,'')),'') is null)::integer
  into v_classrooms_count,v_active_classrooms,v_classrooms_without_code from public.classrooms;
  select count(*)::integer into v_enrollments_count from public.enrollments e join public.profiles p on p.id=e.student_id
  where not (p.role_id='guest' and p.converted_at is null and p.expires_at<=now());
  select count(*)::integer into v_courses_without_classrooms from public.subjects s where not exists(select 1 from public.classrooms c where c.subject_id=s.id);
  select count(*)::integer into v_students_without_activity from (
    select distinct e.student_id from public.enrollments e join public.profiles p on p.id=e.student_id
    where not (p.role_id='guest' and p.converted_at is null and p.expires_at<=now())
      and not exists(select 1 from public.subject_scores ss where ss.student_id=e.student_id)
      and not exists(select 1 from public.attempt_history ah where ah.student_id=e.student_id)
  ) x;
  return jsonb_build_object('totalProfiles',v_total_profiles,'teachersCount',v_teachers_count,'studentsCount',v_students_count,
    'subjectsCount',v_subjects_count,'classroomsCount',v_classrooms_count,'enrollmentsCount',v_enrollments_count,
    'activeCourses',v_active_courses,'archivedCourses',v_archived_courses,'activeClassrooms',v_active_classrooms,
    'inactiveUsers',v_inactive_users,'coursesWithoutClassrooms',v_courses_without_classrooms,
    'studentsWithoutActivity',v_students_without_activity,'classroomsWithoutCode',v_classrooms_without_code);
end $$;
grant execute on function public.get_admin_dashboard_metrics() to authenticated;
notify pgrst,'reload schema';
