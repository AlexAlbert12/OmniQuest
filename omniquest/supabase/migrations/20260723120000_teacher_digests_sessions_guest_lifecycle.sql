create table if not exists public.teacher_digest_deliveries (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  period_start timestamptz not null,
  period_end timestamptz not null,
  frequency text not null check (frequency in ('daily', 'weekly')),
  timezone text not null default 'Europe/Madrid',
  recipient_email text not null,
  status text not null default 'pending' check (status in ('pending','processing','sent','retry','failed','cancelled','unsubscribed')),
  attempts integer not null default 0 check (attempts >= 0),
  max_attempts integer not null default 5 check (max_attempts between 1 and 10),
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by uuid,
  sent_at timestamptz,
  provider_message_id text,
  last_error_code text,
  last_error_message text,
  snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (teacher_id, frequency, period_start, period_end)
);
create index if not exists teacher_digest_due_idx on public.teacher_digest_deliveries(status, next_attempt_at);
create index if not exists teacher_digest_teacher_idx on public.teacher_digest_deliveries(teacher_id, created_at desc);
alter table public.teacher_digest_deliveries enable row level security;
revoke all on public.teacher_digest_deliveries from public, anon, authenticated;

alter table public.user_notification_preferences
  add column if not exists teacher_digest_last_sent_at timestamptz,
  add column if not exists teacher_digest_unsubscribed_at timestamptz;

create or replace function public.enqueue_due_teacher_digests(p_now timestamptz default now())
returns integer language plpgsql security definer set search_path=public as $$
declare v_count integer := 0;
begin
  insert into public.teacher_digest_deliveries(
    teacher_id, period_start, period_end, frequency, timezone, recipient_email, snapshot
  )
  select
    p.id,
    case when np.teacher_digest_frequency='weekly'
      then date_trunc('week', p_now at time zone coalesce(up.timezone,'Europe/Madrid')) at time zone coalesce(up.timezone,'Europe/Madrid')
      else date_trunc('day', p_now at time zone coalesce(up.timezone,'Europe/Madrid')) at time zone coalesce(up.timezone,'Europe/Madrid') end,
    p_now,
    np.teacher_digest_frequency,
    coalesce(up.timezone,'Europe/Madrid'),
    coalesce(nullif(trim(np.teacher_reminder_email),''), au.email),
    jsonb_build_object(
      'inactive_students', case when np.teacher_inactive_student_alerts then (
        select count(distinct e.student_id)
        from public.subjects s join public.enrollments e on e.subject_id=s.id
        join public.profiles sp on sp.id=e.student_id
        where s.teacher_id=p.id and coalesce(s.is_archived,false)=false
          and coalesce(sp.active,true)=true
          and (sp.role_id <> 'guest' or coalesce(sp.expires_at, p_now + interval '1 day') > p_now)
          and not exists (select 1 from public.attempt_history ah where ah.student_id=e.student_id and ah.created_at >= p_now-interval '7 days')
      ) else 0 end,
      'open_reviews', case when np.teacher_open_review_alerts then (
        select count(*) from public.attempt_history ah
        join public.questions q on q.id=ah.question_id
        join public.subjects s on s.id=q.subject_id
        where s.teacher_id=p.id and ah.manual_review_status in ('pending','needs_changes','in_review')
      ) else 0 end,
      'sensitive_actions', case when np.teacher_sensitive_action_alerts then (
        select count(*) from public.teacher_audit_logs tal
        where tal.teacher_id=p.id and tal.created_at >= coalesce(np.teacher_digest_last_sent_at, p_now-interval '7 days')
          and (tal.action ilike '%delete%' or tal.action ilike '%archive%' or tal.action ilike '%password%' or tal.action ilike '%code%' or tal.action ilike '%remove%')
      ) else 0 end,
      'generated_at', p_now
    )
  from public.profiles p
  join auth.users au on au.id=p.id
  join public.user_notification_preferences np on np.user_id=p.id
  left join public.user_preferences up on up.user_id=p.id
  where p.role_id='teacher' and coalesce(p.active,true)
    and np.email_enabled=true
    and np.teacher_digest_frequency in ('daily','weekly')
    and np.teacher_digest_unsubscribed_at is null
    and coalesce(nullif(trim(np.teacher_reminder_email),''), au.email) is not null
    and (
      (np.teacher_digest_frequency='daily' and extract(hour from p_now at time zone coalesce(up.timezone,'Europe/Madrid'))=7
       and (np.teacher_digest_last_sent_at is null or np.teacher_digest_last_sent_at < p_now-interval '20 hours'))
      or
      (np.teacher_digest_frequency='weekly' and extract(isodow from p_now at time zone coalesce(up.timezone,'Europe/Madrid'))=1
       and extract(hour from p_now at time zone coalesce(up.timezone,'Europe/Madrid'))=7
       and (np.teacher_digest_last_sent_at is null or np.teacher_digest_last_sent_at < p_now-interval '6 days'))
    )
  on conflict do nothing;
  get diagnostics v_count = row_count;
  return v_count;
end $$;

create or replace function public.claim_teacher_digest_batch(p_worker_id uuid, p_limit integer default 25)
returns setof public.teacher_digest_deliveries language plpgsql security definer set search_path=public as $$
begin
  return query
  with due as (
    select id from public.teacher_digest_deliveries
    where status in ('pending','retry') and next_attempt_at<=now()
      and attempts<max_attempts
    order by next_attempt_at,id for update skip locked limit greatest(1,least(p_limit,100))
  ), updated as (
    update public.teacher_digest_deliveries d
    set status='processing', attempts=d.attempts+1, locked_at=now(), locked_by=p_worker_id, updated_at=now()
    from due where d.id=due.id returning d.*
  ) select * from updated;
end $$;

create or replace function public.finish_teacher_digest(
  p_id bigint, p_status text, p_provider_message_id text default null,
  p_error_code text default null, p_error_message text default null,
  p_retry_after_seconds integer default null
) returns void language plpgsql security definer set search_path=public as $$
declare v public.teacher_digest_deliveries%rowtype;
begin
  select * into v from public.teacher_digest_deliveries where id=p_id for update;
  if not found then raise exception 'Digest not found'; end if;
  if p_status not in ('sent','retry','failed','cancelled','unsubscribed') then raise exception 'Invalid digest status'; end if;
  update public.teacher_digest_deliveries set
    status=p_status, provider_message_id=coalesce(p_provider_message_id,provider_message_id),
    last_error_code=p_error_code, last_error_message=left(p_error_message,500),
    next_attempt_at=case when p_status='retry' then now()+make_interval(secs=>coalesce(p_retry_after_seconds,300)) else next_attempt_at end,
    sent_at=case when p_status='sent' then now() else sent_at end,
    locked_at=null, locked_by=null, updated_at=now()
  where id=p_id;
  if p_status='sent' then
    update public.user_notification_preferences set teacher_digest_last_sent_at=now(), updated_at=now() where user_id=v.teacher_id;
  elsif p_status='unsubscribed' then
    update public.user_notification_preferences set teacher_digest_unsubscribed_at=now(), teacher_digest_frequency='off', updated_at=now() where user_id=v.teacher_id;
  end if;
end $$;
revoke all on function public.enqueue_due_teacher_digests(timestamptz) from public,anon,authenticated;
revoke all on function public.claim_teacher_digest_batch(uuid,integer) from public,anon,authenticated;
revoke all on function public.finish_teacher_digest(bigint,text,text,text,text,integer) from public,anon,authenticated;
grant execute on function public.enqueue_due_teacher_digests(timestamptz) to service_role;
grant execute on function public.claim_teacher_digest_batch(uuid,integer) to service_role;
grant execute on function public.finish_teacher_digest(bigint,text,text,text,text,integer) to service_role;

