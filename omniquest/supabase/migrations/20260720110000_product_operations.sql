-- Usage analytics, admin support operations and role-aware global search.

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  role text,
  event_name text not null,
  subject_id bigint references public.subjects(id) on delete set null,
  classroom_id bigint references public.classrooms(id) on delete set null,
  topic_id bigint references public.subject_topics(id) on delete set null,
  attempt_id uuid references public.game_attempts(id) on delete set null,
  session_id text,
  properties jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists analytics_events_name_occurred_at_idx
  on public.analytics_events(event_name, occurred_at desc);
create index if not exists analytics_events_user_occurred_at_idx
  on public.analytics_events(user_id, occurred_at desc);
create index if not exists analytics_events_subject_occurred_at_idx
  on public.analytics_events(subject_id, occurred_at desc)
  where subject_id is not null;

alter table public.analytics_events enable row level security;

revoke all on table public.analytics_events from anon, authenticated;
grant select on table public.analytics_events to authenticated;

drop policy if exists "admin_select_analytics_events" on public.analytics_events;
create policy "admin_select_analytics_events"
on public.analytics_events for select to authenticated
using (public.is_admin());

create or replace function public.track_usage_event(
  p_event_name text,
  p_properties jsonb default '{}'::jsonb,
  p_subject_id bigint default null,
  p_classroom_id bigint default null,
  p_topic_id bigint default null,
  p_attempt_id uuid default null,
  p_session_id text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_role text;
  v_event_name text := lower(trim(coalesce(p_event_name, '')));
  v_event_id bigint;
begin
  if v_user_id is null then
    raise exception 'No authenticated user';
  end if;

  if v_event_name not in (
    'game_error',
    'game_resumed',
    'global_search',
    'support_ticket_created'
  ) then
    raise exception 'Unsupported analytics event';
  end if;

  select role_id into v_role
  from public.profiles
  where id = v_user_id;

  insert into public.analytics_events (
    user_id,
    role,
    event_name,
    subject_id,
    classroom_id,
    topic_id,
    attempt_id,
    session_id,
    properties
  ) values (
    v_user_id,
    v_role,
    v_event_name,
    p_subject_id,
    p_classroom_id,
    p_topic_id,
    p_attempt_id,
    nullif(trim(coalesce(p_session_id, '')), ''),
    coalesce(p_properties, '{}'::jsonb)
  )
  returning id into v_event_id;

  return v_event_id;
end;
$$;

revoke execute on function public.track_usage_event(text, jsonb, bigint, bigint, bigint, uuid, text) from public, anon;
grant execute on function public.track_usage_event(text, jsonb, bigint, bigint, bigint, uuid, text) to authenticated;

create or replace function public.log_game_attempt_analytics()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text;
  v_event_name text;
begin
  select role_id into v_role
  from public.profiles
  where id = new.student_id;

  if tg_op = 'INSERT' then
    v_event_name := 'game_started';
  elsif tg_op = 'UPDATE' and old.status is distinct from new.status then
    if new.status = 'abandoned' then
      v_event_name := 'game_abandoned';
    elsif new.status = 'finished' then
      v_event_name := 'game_finished';
    end if;
  end if;

  if v_event_name is not null then
    insert into public.analytics_events (
      user_id,
      role,
      event_name,
      subject_id,
      classroom_id,
      topic_id,
      attempt_id,
      properties,
      occurred_at
    ) values (
      new.student_id,
      coalesce(v_role, 'student'),
      v_event_name,
      new.subject_id,
      new.classroom_id,
      new.topic_id,
      new.id,
      jsonb_build_object(
        'status', new.status,
        'total_score', coalesce(new.total_score, 0),
        'correct_answers', coalesce(new.correct_answers, 0)
      ),
      case
        when v_event_name in ('game_finished', 'game_abandoned') then coalesce(new.finished_at, now())
        else coalesce(new.started_at, now())
      end
    );
  end if;

  return new;
end;
$$;

drop trigger if exists log_game_attempt_analytics_insert on public.game_attempts;
create trigger log_game_attempt_analytics_insert
after insert on public.game_attempts
for each row execute function public.log_game_attempt_analytics();

drop trigger if exists log_game_attempt_analytics_status on public.game_attempts;
create trigger log_game_attempt_analytics_status
after update of status on public.game_attempts
for each row execute function public.log_game_attempt_analytics();

