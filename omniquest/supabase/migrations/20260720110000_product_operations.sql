-- One role-aware global search RPC avoids duplicating search logic in every screen.
create or replace function public.search_app_entities(
  p_query text,
  p_limit integer default 12
)
returns table (
  entity_type text,
  entity_id text,
  title text,
  subtitle text,
  role_id text,
  subject_id bigint,
  classroom_id bigint,
  relevance integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_role text;
  v_query text := lower(trim(coalesce(p_query, '')));
  v_limit integer := least(greatest(coalesce(p_limit, 12), 1), 30);
begin
  if v_user_id is null then
    raise exception 'No authenticated user';
  end if;

  if length(v_query) < 2 then
    return;
  end if;

  select p.role_id into v_role
  from public.profiles p
  where p.id = v_user_id and coalesce(p.active, true);

  if v_role = 'admin' then
    return query
    with candidates as (
      select
        'profile'::text as entity_type,
        p.id::text as entity_id,
        coalesce(p.alias, p.email, 'Usuario')::text as title,
        concat_ws(' · ', case when p.role_id = 'teacher' then 'Profesor' else 'Alumno' end, p.email)::text as subtitle,
        p.role_id::text as role_id,
        null::bigint as subject_id,
        null::bigint as classroom_id,
        case
          when lower(coalesce(p.alias, '')) = v_query then 0
          when lower(coalesce(p.alias, '')) like v_query || '%' then 1
          else 3
        end as relevance
      from public.profiles p
      where p.role_id in ('teacher', 'student', 'guest')
        and lower(concat_ws(' ', p.alias, p.email, p.role_id)) like '%' || v_query || '%'

      union all

      select
        'subject',
        s.id::text,
        s.name,
        concat_ws(' · ', 'Curso', p.alias, case when coalesce(s.is_archived, false) then 'Archivado' else null end),
        null,
        s.id,
        null,
        case when lower(s.name) = v_query then 0 when lower(s.name) like v_query || '%' then 1 else 3 end
      from public.subjects s
      left join public.profiles p on p.id = s.teacher_id
      where lower(concat_ws(' ', s.name, s.code, p.alias, p.email)) like '%' || v_query || '%'

      union all

      select
        'classroom',
        c.id::text,
        c.name,
        concat_ws(' · ', 'Clase', s.name, c.code),
        null,
        c.subject_id,
        c.id,
        case when lower(c.name) = v_query then 0 when lower(c.name) like v_query || '%' then 1 else 3 end
      from public.classrooms c
      join public.subjects s on s.id = c.subject_id
      where lower(concat_ws(' ', c.name, c.code, s.name)) like '%' || v_query || '%'
    )
    select c.entity_type, c.entity_id, c.title, c.subtitle, c.role_id, c.subject_id, c.classroom_id, c.relevance
    from candidates c
    order by c.relevance, c.title
    limit v_limit;
    return;
  end if;

  if v_role = 'teacher' then
    return query
    with teacher_subjects as (
      select s.id, s.name, s.code
      from public.subjects s
      where s.teacher_id = v_user_id
    ),
    student_candidates as (
      select distinct on (p.id)
        'profile'::text as entity_type,
        p.id::text as entity_id,
        coalesce(p.alias, p.email, 'Alumno')::text as title,
        concat_ws(' · ', 'Alumno', p.email, ts.name)::text as subtitle,
        p.role_id::text as role_id,
        ts.id::bigint as subject_id,
        e.classroom_id::bigint as classroom_id,
        case
          when lower(coalesce(p.alias, '')) = v_query then 0
          when lower(coalesce(p.alias, '')) like v_query || '%' then 1
          else 3
        end as relevance
      from public.enrollments e
      join teacher_subjects ts on ts.id = e.subject_id
      join public.profiles p on p.id = e.student_id
      where lower(concat_ws(' ', p.alias, p.email, ts.name)) like '%' || v_query || '%'
      order by p.id, ts.id
    ),
    candidates as (
      select * from student_candidates

      union all

      select
        'subject',
        ts.id::text,
        ts.name,
        concat_ws(' · ', 'Curso', ts.code),
        null,
        ts.id,
        null,
        case when lower(ts.name) = v_query then 0 when lower(ts.name) like v_query || '%' then 1 else 3 end
      from teacher_subjects ts
      where lower(concat_ws(' ', ts.name, ts.code)) like '%' || v_query || '%'

      union all

      select
        'classroom',
        c.id::text,
        c.name,
        concat_ws(' · ', 'Clase', ts.name, c.code),
        null,
        c.subject_id,
        c.id,
        case when lower(c.name) = v_query then 0 when lower(c.name) like v_query || '%' then 1 else 3 end
      from public.classrooms c
      join teacher_subjects ts on ts.id = c.subject_id
      where lower(concat_ws(' ', c.name, c.code, ts.name)) like '%' || v_query || '%'
    )
    select c.entity_type, c.entity_id, c.title, c.subtitle, c.role_id, c.subject_id, c.classroom_id, c.relevance
    from candidates c
    order by c.relevance, c.title
    limit v_limit;
    return;
  end if;

  raise exception 'Global search is available only to teachers and admins';
end;
$$;

