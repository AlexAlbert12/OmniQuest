create or replace function public.get_admin_support_tickets_page(
  p_search text default null,
  p_status text default null,
  p_priority text default null,
  p_role text default null,
  p_limit integer default 25,
  p_offset integer default 0
)
returns table (
  id bigint,
  user_id uuid,
  user_alias text,
  user_email text,
  role text,
  category text,
  subject text,
  message text,
  contact_email text,
  priority text,
  status text,
  admin_response text,
  assigned_admin_id uuid,
  resolved_at timestamptz,
  last_response_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  total_count bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 25), 1), 100);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_search text := nullif(trim(coalesce(p_search, '')), '');
  v_status text := nullif(lower(trim(coalesce(p_status, ''))), '');
  v_priority text := nullif(lower(trim(coalesce(p_priority, ''))), '');
  v_role text := nullif(lower(trim(coalesce(p_role, ''))), '');
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  return query
  with filtered as (
    select t.*, p.alias as user_alias, p.email as user_email
    from public.user_support_tickets t
    left join public.profiles p on p.id = t.user_id
    where (v_status is null or t.status = v_status)
      and (v_priority is null or t.priority = v_priority)
      and (v_role is null or t.role = v_role)
      and (
        v_search is null
        or concat_ws(' ', t.subject, t.message, t.category, t.contact_email, t.admin_response, p.alias, p.email) ilike '%' || v_search || '%'
      )
  )
  select
    f.id,
    f.user_id,
    f.user_alias,
    f.user_email,
    f.role,
    f.category,
    f.subject,
    f.message,
    f.contact_email,
    f.priority,
    f.status,
    f.admin_response,
    f.assigned_admin_id,
    f.resolved_at,
    f.last_response_at,
    f.created_at,
    f.updated_at,
    count(*) over() as total_count
  from filtered f
  order by
    case f.priority when 'high' then 1 when 'medium' then 2 else 3 end,
    case f.status when 'open' then 1 when 'in_progress' then 2 when 'resolved' then 3 else 4 end,
    f.created_at desc,
    f.id desc
  limit v_limit offset v_offset;
end;
$$;

create or replace function public.admin_update_support_ticket(
  p_ticket_id bigint,
  p_status text,
  p_priority text default null,
  p_admin_response text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := auth.uid();
  v_ticket public.user_support_tickets%rowtype;
  v_status text := lower(trim(coalesce(p_status, '')));
  v_priority text := nullif(lower(trim(coalesce(p_priority, ''))), '');
  v_response text := nullif(trim(coalesce(p_admin_response, '')), '');
  v_audience text;
  v_action_url text;
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  if v_status not in ('open', 'in_progress', 'resolved', 'closed') then
    raise exception 'Invalid support status';
  end if;

  if v_priority is not null and v_priority not in ('low', 'medium', 'high') then
    raise exception 'Invalid support priority';
  end if;

  update public.user_support_tickets
  set
    status = v_status,
    priority = coalesce(v_priority, priority),
    admin_response = coalesce(v_response, admin_response),
    assigned_admin_id = v_admin_id,
    last_response_at = case when v_response is not null then now() else last_response_at end,
    resolved_at = case when v_status in ('resolved', 'closed') then coalesce(resolved_at, now()) else null end,
    updated_at = now()
  where id = p_ticket_id
  returning * into v_ticket;

  if not found then
    raise exception 'Support ticket not found';
  end if;

  insert into public.admin_audit_logs (admin_id, action, target_table, target_id, metadata)
  values (
    v_admin_id,
    'admin.support.update',
    'user_support_tickets',
    v_ticket.id::text,
    jsonb_build_object(
      'status', v_ticket.status,
      'priority', v_ticket.priority,
      'user_id', v_ticket.user_id,
      'has_response', v_ticket.admin_response is not null
    )
  );

  if v_response is not null then
    v_audience := case when v_ticket.role = 'teacher' then 'teacher' else 'student' end;
    v_action_url := case when v_audience = 'teacher' then '/(teacher)/help-center' else '/(student)/help-center' end;

    perform public.create_notification(
      v_ticket.user_id,
      v_audience,
      'announcement',
      'Soporte ha respondido',
      concat('Tu ticket "', v_ticket.subject, '" tiene una nueva respuesta.'),
      'chatbubble-ellipses-outline',
      '#8B5CF6',
      v_action_url,
      'user_support_tickets',
      v_ticket.id::text,
      jsonb_build_object(
        'ticket_id', v_ticket.id,
        'status', v_ticket.status,
        'preference_category', 'system'
      ),
      concat(
        'support-ticket:',
        v_ticket.id,
        ':response:',
        coalesce(v_ticket.last_response_at, now())::text
      )
    );
  end if;

  return jsonb_build_object(
    'id', v_ticket.id,
    'status', v_ticket.status,
    'priority', v_ticket.priority,
    'admin_response', v_ticket.admin_response,
    'updated_at', v_ticket.updated_at
  );
end;
$$;

