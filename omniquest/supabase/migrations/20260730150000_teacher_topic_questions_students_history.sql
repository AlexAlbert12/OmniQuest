    select attempted_at::date as day, count(*)::int as attempts,
      count(*) filter (where is_correct)::int as correct,
      coalesce(sum(coalesce(earned_points, 0)), 0)::int as earned_xp
    from attempts group by attempted_at::date order by day
  ), topic_rows as (
    select subject_id, subject_name, topic_id, topic_title, count(*)::int as attempts,
      count(*) filter (where is_correct)::int as correct,
      round(100.0 * count(*) filter (where is_correct) / nullif(count(*), 0))::int as accuracy_percent,
      coalesce(sum(coalesce(earned_points, 0)), 0)::int as earned_xp,
      max(attempted_at) as last_activity_at
    from attempts group by subject_id, subject_name, topic_id, topic_title
  )
  select jsonb_build_object(
    'periodDays', v_days,
    'evolution', coalesce((
      select jsonb_agg(jsonb_build_object(
        'date', d.day,
        'attempts', d.attempts,
        'correct', d.correct,
        'accuracyPercent', case when d.attempts > 0 then round(100.0 * d.correct / d.attempts)::int else 0 end,
        'earnedXp', d.earned_xp
      ) order by d.day) from daily d
    ), '[]'::jsonb),
    'topics', coalesce((select jsonb_agg(to_jsonb(t) order by t.last_activity_at desc, t.topic_title) from topic_rows t), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;

create or replace function public.add_teacher_student_note(
  p_student_id uuid,
  p_body text,
  p_subject_id bigint default null,
  p_classroom_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_teacher_id uuid := auth.uid();
  v_note public.teacher_student_notes%rowtype;
begin
  if v_teacher_id is null then raise exception 'Teacher session required'; end if;
  if nullif(trim(coalesce(p_body, '')), '') is null then raise exception 'Write a note'; end if;
  if not exists (
    select 1 from public.enrollments e join public.subjects s on s.id = e.subject_id
    where e.student_id = p_student_id and s.teacher_id = v_teacher_id
      and (p_subject_id is null or e.subject_id = p_subject_id)
      and (p_classroom_id is null or e.classroom_id = p_classroom_id)
  ) then raise exception 'Student not found or access denied'; end if;

  insert into public.teacher_student_notes(teacher_id, student_id, subject_id, classroom_id, body)
  values (v_teacher_id, p_student_id, p_subject_id, p_classroom_id, trim(p_body))
  returning * into v_note;

  insert into public.teacher_audit_logs(teacher_id, action, target_table, target_id, metadata)
  values (v_teacher_id, 'teacher.student.note.add', 'profiles', p_student_id::text,
    jsonb_build_object('note_id', v_note.id, 'subject_id', p_subject_id, 'classroom_id', p_classroom_id));

  return jsonb_build_object(
    'id', v_note.id,
    'body', v_note.body,
    'subjectId', v_note.subject_id,
    'classroomId', v_note.classroom_id,
    'createdAt', v_note.created_at,
    'updatedAt', v_note.updated_at
  );
end;
$$;

