create or replace function public.prepare_manual_review_sla()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_teacher_id uuid;
  v_sla_hours integer := 48;
begin
  if new.manual_review_status in ('pending', 'in_review', 'needs_changes') then
    select s.teacher_id into v_teacher_id
    from public.questions q
    join public.subjects s on s.id = q.subject_id
    where q.id = new.question_id;

    select coalesce(mrs.sla_hours, 48) into v_sla_hours
    from public.manual_review_settings mrs
    where mrs.teacher_id = v_teacher_id;
    v_sla_hours := coalesce(v_sla_hours, 48);

    if new.manual_review_due_at is null then
      new.manual_review_due_at := coalesce(new.attempted_at, new.created_at, now()) + make_interval(hours => v_sla_hours);
    end if;
    if new.manual_review_status = 'in_review' and new.manual_review_started_at is null then
      new.manual_review_started_at := now();
    end if;
  else
    new.manual_review_due_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists prepare_manual_review_sla_trigger on public.attempt_history;
create trigger prepare_manual_review_sla_trigger
before insert or update of manual_review_status, question_id on public.attempt_history
for each row execute function public.prepare_manual_review_sla();

update public.attempt_history ah
set manual_review_due_at = coalesce(ah.attempted_at, ah.created_at, now()) + interval '48 hours'
where ah.manual_review_status in ('pending', 'in_review', 'needs_changes')
  and ah.manual_review_due_at is null;

create or replace function public.capture_manual_review_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_changed boolean;
  v_event text;
begin
  v_changed := old.manual_review_status is distinct from new.manual_review_status
    or old.manual_review_assigned_to is distinct from new.manual_review_assigned_to
    or old.manual_review_rubric_id is distinct from new.manual_review_rubric_id
    or old.manual_review_rubric_result is distinct from new.manual_review_rubric_result
    or old.earned_points is distinct from new.earned_points;
  if not v_changed then return new; end if;

  v_event := case
    when old.manual_review_status is distinct from new.manual_review_status then 'status_changed'
    when old.manual_review_assigned_to is distinct from new.manual_review_assigned_to then 'assigned'
    when old.manual_review_rubric_result is distinct from new.manual_review_rubric_result then 'rubric_scored'
    else 'review_updated'
  end;

  insert into public.manual_review_history(
    attempt_history_id, actor_id, event_type, from_status, to_status, before_state, after_state
  ) values (
    new.id,
    auth.uid(),
    v_event,
    old.manual_review_status,
    new.manual_review_status,
    jsonb_build_object(
      'status', old.manual_review_status,
      'assigned_to', old.manual_review_assigned_to,
      'rubric_id', old.manual_review_rubric_id,
      'earned_points', old.earned_points
    ),
    jsonb_build_object(
      'status', new.manual_review_status,
      'assigned_to', new.manual_review_assigned_to,
      'rubric_id', new.manual_review_rubric_id,
      'earned_points', new.earned_points
    )
  );
  return new;
end;
$$;

drop trigger if exists capture_manual_review_history_trigger on public.attempt_history;
create trigger capture_manual_review_history_trigger
after update of manual_review_status, manual_review_assigned_to, manual_review_rubric_id, manual_review_rubric_result, earned_points
on public.attempt_history
for each row execute function public.capture_manual_review_history();

