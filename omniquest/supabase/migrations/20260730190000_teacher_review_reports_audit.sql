create or replace function public.save_teacher_audit_filter(p_id uuid,p_name text,p_filters jsonb)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_user_id uuid:=auth.uid(); v_id uuid;
begin
  if p_id is null then insert into public.teacher_audit_saved_filters(teacher_id,name,filters) values(v_user_id,trim(p_name),p_filters) on conflict(teacher_id,name) do update set filters=excluded.filters,updated_at=now() returning id into v_id;
