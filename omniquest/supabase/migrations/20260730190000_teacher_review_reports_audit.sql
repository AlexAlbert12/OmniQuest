create or replace function public.assign_manual_review_attempts(p_attempt_ids bigint[], p_assignee_id uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user_id uuid := auth.uid(); v_count integer;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if p_assignee_id is not null and not exists (select 1 from public.profiles where id = p_assignee_id and role_id = 'teacher' and coalesce(active, true)) then raise exception 'Invalid assignee'; end if;
  update public.attempt_history ah
  set manual_review_assigned_to = p_assignee_id
  from public.questions q join public.subjects s on s.id = q.subject_id
  where ah.question_id = q.id and ah.id = any(coalesce(p_attempt_ids, '{}'::bigint[]))
    and (s.teacher_id = v_user_id or public.is_admin() or ah.manual_review_assigned_to = v_user_id)
    and ah.manual_review_status in ('pending', 'in_review', 'needs_changes');
  get diagnostics v_count = row_count;
  if p_assignee_id is not null and p_assignee_id <> v_user_id and v_count > 0 then
    perform public.create_notification(p_assignee_id, 'teacher', 'manual_review', 'Revisiones asignadas', format('Se te han asignado %s respuestas abiertas.', v_count), 'create-outline', '#38BDF8', '/(teacher)/reviews', 'attempt_history', null, jsonb_build_object('count', v_count, 'preference_category', 'system'), 'manual-review-assignment:' || p_assignee_id::text || ':' || extract(epoch from date_trunc('minute', now()))::bigint::text);
  end if;
  return jsonb_build_object('updated', v_count);
end;
$$;

create or replace function public.get_manual_review_thread(p_attempt_history_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_student_id uuid;
  v_teacher_id uuid;
  v_assignee_id uuid;
  v_result jsonb;
begin
  if v_user_id is null then raise exception 'No hay sesión activa.'; end if;

  select ah.student_id, s.teacher_id, ah.manual_review_assigned_to
  into v_student_id, v_teacher_id, v_assignee_id
  from public.attempt_history ah
  join public.questions q on q.id = ah.question_id
  join public.subjects s on s.id = q.subject_id
  where ah.id = p_attempt_history_id;

  if not found then raise exception 'Intento no encontrado.'; end if;
  if v_user_id <> v_student_id and v_user_id <> v_teacher_id and v_user_id is distinct from v_assignee_id and not public.is_admin() then
    raise exception 'No puedes consultar esta revisión.';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', c.id,
    'author_id', c.author_id,
    'author_name', coalesce(p.alias, split_part(p.email, '@', 1), 'Usuario'),
    'audience', c.audience,
    'body', c.body,
    'created_at', c.created_at
  ) order by c.created_at asc, c.id asc), '[]'::jsonb)
  into v_result
  from public.manual_review_comments c
  left join public.profiles p on p.id = c.author_id
  where c.attempt_history_id = p_attempt_history_id
    and (v_user_id = v_teacher_id or v_user_id = v_assignee_id or public.is_admin() or c.audience = 'student');

  return v_result;
end;
$$;

