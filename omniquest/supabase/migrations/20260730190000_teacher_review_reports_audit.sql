create or replace function public.apply_teacher_audit_retention()
returns integer language plpgsql security definer set search_path=public as $$
declare v_days integer; v_count integer;
begin
  select retention_days into v_days from public.teacher_audit_retention_policy where singleton=true;
  perform set_config('omniquest.audit_retention','on',true);
  delete from public.teacher_audit_logs where created_at < now() - make_interval(days=>coalesce(v_days,730));
  get diagnostics v_count=row_count;
  return v_count;
end;
$$;

create or replace function public.detect_teacher_audit_anomalies()
returns integer language plpgsql security definer set search_path=public as $$
declare v_count integer := 0; v_added integer := 0;
begin
  insert into public.teacher_audit_alerts(teacher_id,pattern_key,severity,title,description,window_started_at,window_ended_at,event_count)
  select teacher_id,'destructive-burst','critical','Patrón destructivo inusual',format('%s acciones destructivas en 15 minutos.',count(*)),date_trunc('minute',now()-interval '15 minutes'),date_trunc('minute',now()),count(*)::integer
  from public.teacher_audit_logs where created_at>=now()-interval '15 minutes' and (action ilike '%delete%' or action ilike '%archive%' or action ilike '%deactivate%' or severity='critical')
  group by teacher_id having count(*)>=8
  on conflict do nothing;
  get diagnostics v_added=row_count;
  v_count := v_count + v_added;

  insert into public.teacher_audit_alerts(teacher_id,pattern_key,severity,title,description,window_started_at,window_ended_at,event_count)
  select teacher_id,'code-burst','warning','Generación elevada de códigos',format('%s acciones sobre códigos en una hora.',count(*)),date_trunc('hour',now()-interval '1 hour'),date_trunc('hour',now()),count(*)::integer
  from public.teacher_audit_logs where created_at>=now()-interval '1 hour' and (action ilike '%code%' or target_table='classrooms')
  group by teacher_id having count(*)>=20
  on conflict do nothing;
  get diagnostics v_added=row_count;
  v_count := v_count + v_added;
  return v_count;
end;
$$;

create or replace function public.get_teacher_audit_logs_page_v2(
  p_category text default 'all', p_search text default null, p_action text default null, p_target_table text default null,
  p_severity text default null, p_from timestamptz default null, p_to timestamptz default null, p_limit integer default 25, p_offset integer default 0
)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user_id uuid:=auth.uid(); v_limit integer:=least(greatest(coalesce(p_limit,25),1),100); v_offset integer:=greatest(coalesce(p_offset,0),0); v_result jsonb;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  with filtered as (
    select l.* from public.teacher_audit_logs l where (public.is_admin() or l.teacher_id=v_user_id)
      and (coalesce(nullif(p_category,''),'all')='all'
        or (p_category='student' and (l.target_table in ('profiles','enrollments','subject_scores','topic_scores') or l.action ilike '%student%'))
        or (p_category='question' and (l.target_table in ('questions','answers') or l.action ilike '%question%'))
        or (p_category='subject' and (l.target_table in ('subjects','subject_topics') or l.action ilike any(array['%subject%','%course%','%topic%'])))
        or (p_category='code' and (l.action ilike '%code%' or l.target_table='classrooms'))
        or (p_category='profile' and (l.action ilike '%profile%' or l.target_table='profiles')))
      and (nullif(trim(coalesce(p_search,'')),'') is null or concat_ws(' ',l.action,l.target_table,l.target_id,l.metadata::text) ilike '%'||trim(p_search)||'%')
      and (nullif(trim(coalesce(p_action,'')),'') is null or l.action=p_action)
      and (nullif(trim(coalesce(p_target_table,'')),'') is null or l.target_table=p_target_table)
      and (nullif(trim(coalesce(p_severity,'')),'') is null or l.severity=p_severity)
      and (p_from is null or l.created_at>=p_from) and (p_to is null or l.created_at<p_to)
  ), page as (select * from filtered order by created_at desc,id desc limit v_limit offset v_offset)
  select jsonb_build_object(
    'items',coalesce((select jsonb_agg(jsonb_build_object('id',p.id,'teacher_id',p.teacher_id,'action',p.action,'target_table',p.target_table,'target_id',p.target_id,'metadata',p.metadata,'before_state',p.before_state,'after_state',p.after_state,'severity',p.severity,'request_id',p.request_id,'created_at',p.created_at) order by p.created_at desc,p.id desc) from page p),'[]'::jsonb),
    'total',(select count(*) from filtered),
    'stats',jsonb_build_object('last7Days',(select count(*) from filtered where created_at>=now()-interval '7 days'),'critical',(select count(*) from filtered where severity='critical'),'warning',(select count(*) from filtered where severity='warning')),
    'actions',coalesce((select jsonb_agg(distinct action) from filtered),'[]'::jsonb),
    'targetTables',coalesce((select jsonb_agg(distinct target_table) from filtered where target_table is not null),'[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;

