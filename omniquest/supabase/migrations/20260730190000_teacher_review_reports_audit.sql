create or replace function public.get_teacher_manual_review_queue(
  p_subject_id bigint default null,
  p_classroom_id bigint default null,
  p_status text default null,
  p_search text default null,
  p_limit integer default 20,
  p_offset integer default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 100);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_result jsonb;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;

  with filtered as (
    select
      ah.id,
      ah.student_id,
      coalesce(p.alias, split_part(p.email, '@', 1), 'Alumno') as student_name,
      p.email as student_email,
      ah.question_id,
      q.text as question_text,
      ah.submitted_answer_text as answer_text,
      ah.submitted_answer_payload as answer_payload,
      ah.manual_review_status as status,
      ah.attempted_at,
      ah.reviewed_at,
      ah.review_notes,
      ah.earned_points,
      q.points_base as possible_points,
      ah.time_taken_seconds,
      s.id as subject_id,
      s.name as subject_name,
      c.id as classroom_id,
      coalesce(c.name, 'Sin clase') as classroom_name,
      st.id as topic_id,
      st.title as topic_name,
      ah.manual_review_due_at as due_at,
      ah.manual_review_assigned_to as assigned_to,
      coalesce(assignee.alias, split_part(assignee.email, '@', 1)) as assigned_to_name,
      ah.manual_review_rubric_id as rubric_id,
      rubric.name as rubric_name,
      ah.manual_review_rubric_result as rubric_result,
      greatest(0, extract(epoch from (now() - coalesce(ah.attempted_at, ah.created_at, now())))::bigint) as pending_seconds,
      (ah.manual_review_due_at is not null and ah.manual_review_due_at < now()) as is_overdue,
      (select count(*) from public.manual_review_comments mrc where mrc.attempt_history_id = ah.id)::integer as comments_count,
      (select mrc.body from public.manual_review_comments mrc where mrc.attempt_history_id = ah.id order by mrc.created_at desc, mrc.id desc limit 1) as latest_comment
    from public.attempt_history ah
    join public.questions q on q.id = ah.question_id
    join public.subjects s on s.id = q.subject_id
    left join public.classrooms c on c.id = coalesce(q.classroom_id, (select ga.classroom_id from public.game_attempts ga where ga.id = ah.attempt_id))
    left join public.subject_topics st on st.id = q.topic_id
    left join public.profiles p on p.id = ah.student_id
    left join public.profiles assignee on assignee.id = ah.manual_review_assigned_to
    left join public.manual_review_rubrics rubric on rubric.id = ah.manual_review_rubric_id
    where q.type = 'open_answer'
      and ah.manual_review_status <> 'not_required'
      and (public.is_admin() or s.teacher_id = v_user_id or ah.manual_review_assigned_to = v_user_id)
      and (p_subject_id is null or q.subject_id = p_subject_id)
      and (p_classroom_id is null or coalesce(q.classroom_id, c.id) = p_classroom_id)
      and (nullif(trim(coalesce(p_status, '')), '') is null or ah.manual_review_status = p_status)
      and (
        nullif(trim(coalesce(p_search, '')), '') is null
        or q.text ilike '%' || trim(p_search) || '%'
        or coalesce(ah.submitted_answer_text, '') ilike '%' || trim(p_search) || '%'
        or coalesce(p.alias, '') ilike '%' || trim(p_search) || '%'
        or coalesce(p.email, '') ilike '%' || trim(p_search) || '%'
        or s.name ilike '%' || trim(p_search) || '%'
      )
  ), page as (
    select * from filtered
    order by is_overdue desc,
      case status when 'pending' then 1 when 'needs_changes' then 2 when 'in_review' then 3 else 4 end,
      due_at asc nulls last, attempted_at asc, id asc
    limit v_limit offset v_offset
  )
  select jsonb_build_object(
    'items', coalesce((select jsonb_agg(to_jsonb(page) order by page.is_overdue desc, page.due_at asc nulls last, page.id) from page), '[]'::jsonb),
    'total', (select count(*) from filtered),
    'summary', jsonb_build_object(
      'pending', (select count(*) from filtered where status = 'pending'),
      'in_review', (select count(*) from filtered where status = 'in_review'),
      'needs_changes', (select count(*) from filtered where status = 'needs_changes'),
      'overdue', (select count(*) from filtered where is_overdue)
    )
  ) into v_result;
  return coalesce(v_result, jsonb_build_object('items', '[]'::jsonb, 'total', 0, 'summary', '{}'::jsonb));
end;
$$;

create or replace function public.get_manual_review_configuration()
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user_id uuid := auth.uid(); v_result jsonb;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if not public.is_admin() and not exists (select 1 from public.profiles where id = v_user_id and role_id = 'teacher') then
    raise exception 'Teacher access required';
  end if;
  insert into public.manual_review_settings(teacher_id) values (v_user_id) on conflict (teacher_id) do nothing;

  select jsonb_build_object(
    'slaHours', (select sla_hours from public.manual_review_settings where teacher_id = v_user_id),
    'rubrics', coalesce((select jsonb_agg(to_jsonb(r) order by r.updated_at desc) from public.manual_review_rubrics r where r.teacher_id = v_user_id and r.active), '[]'::jsonb),
    'templates', coalesce((select jsonb_agg(to_jsonb(t) order by t.updated_at desc) from public.manual_review_comment_templates t where t.teacher_id = v_user_id and t.active), '[]'::jsonb),
    'savedFilters', coalesce((select jsonb_agg(to_jsonb(f) order by f.updated_at desc) from public.manual_review_saved_filters f where f.teacher_id = v_user_id), '[]'::jsonb),
    'assignees', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'name', coalesce(p.alias, split_part(p.email, '@', 1), 'Profesor')) order by p.alias) from public.profiles p where p.role_id = 'teacher' and coalesce(p.active, true)), '[]'::jsonb),
    'subjects', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'name', s.name) order by s.name) from public.subjects s where s.teacher_id = v_user_id and not s.is_archived), '[]'::jsonb),
    'classrooms', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'subject_id', c.subject_id, 'name', c.name) order by c.name) from public.classrooms c join public.subjects s on s.id = c.subject_id where s.teacher_id = v_user_id and c.active), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;

create or replace function public.save_manual_review_settings(p_sla_hours integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user_id uuid := auth.uid();
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if p_sla_hours not between 1 and 720 then raise exception 'Invalid SLA'; end if;
  insert into public.manual_review_settings(teacher_id, sla_hours, updated_at)
  values (v_user_id, p_sla_hours, now())
  on conflict (teacher_id) do update set sla_hours = excluded.sla_hours, updated_at = now();
  return jsonb_build_object('slaHours', p_sla_hours);
end;
$$;

create or replace function public.save_manual_review_rubric(p_id uuid, p_name text, p_subject_id bigint, p_criteria jsonb)
returns uuid language plpgsql security definer set search_path = public as $$
declare v_user_id uuid := auth.uid(); v_id uuid;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if jsonb_typeof(p_criteria) <> 'array' or jsonb_array_length(p_criteria) = 0 then raise exception 'Rubric requires criteria'; end if;
  if p_subject_id is not null and not exists (select 1 from public.subjects where id = p_subject_id and teacher_id = v_user_id) then raise exception 'Invalid subject'; end if;
  if p_id is null then
    insert into public.manual_review_rubrics(teacher_id, subject_id, name, criteria)
    values (v_user_id, p_subject_id, trim(p_name), p_criteria) returning id into v_id;
  else
    update public.manual_review_rubrics set subject_id = p_subject_id, name = trim(p_name), criteria = p_criteria, updated_at = now()
    where id = p_id and teacher_id = v_user_id returning id into v_id;
    if v_id is null then raise exception 'Rubric not found'; end if;
  end if;
  return v_id;
end;
$$;

