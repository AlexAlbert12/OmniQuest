  into v_result from public.manual_review_history h left join public.profiles p on p.id = h.actor_id where h.attempt_history_id = p_attempt_history_id;
  return v_result;
end;
$$;

create or replace function public.get_teacher_question_report(
  p_question_id bigint,
  p_classroom_id bigint default null,
  p_date_from timestamptz default null,
  p_date_to timestamptz default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user_id uuid := auth.uid(); v_subject_id bigint; v_result jsonb;
begin
  select q.subject_id into v_subject_id
  from public.questions q join public.subjects s on s.id = q.subject_id
  where q.id = p_question_id and (public.is_admin() or s.teacher_id = v_user_id);
  if not found then raise exception 'Question report access denied'; end if;

  with attempts as (
    select ah.*, coalesce(ga.classroom_id, q.classroom_id) as resolved_classroom_id
    from public.attempt_history ah
    join public.questions q on q.id = ah.question_id
    left join public.game_attempts ga on ga.id = ah.attempt_id
    where ah.question_id = p_question_id
      and (p_classroom_id is null or coalesce(ga.classroom_id, q.classroom_id) = p_classroom_id)
      and (p_date_from is null or ah.attempted_at >= p_date_from)
      and (p_date_to is null or ah.attempted_at < p_date_to)
  ), summary as (
    select count(*)::integer total_attempts,
      count(*) filter (where is_correct)::integer correct_attempts,
      count(*) filter (where not is_correct)::integer failed_attempts,
      count(*) filter (where was_skipped)::integer skipped_attempts,
      count(distinct student_id)::integer sample_size,
      round(avg(time_taken_seconds) filter (where time_taken_seconds is not null), 1) average_time_seconds,
      round(100.0 * count(*) filter (where was_skipped) / nullif(count(*), 0), 1) abandonment_percent
    from attempts
  ), answer_distribution as (
    select coalesce(a.text, case when at.was_skipped then 'Omitida' when q.type = 'open_answer' then 'Respuesta libre' else 'Respuesta interactiva' end) label,
      count(*)::integer count,
      bool_or(coalesce(a.is_correct, at.is_correct)) correct
    from attempts at join public.questions q on q.id = at.question_id left join public.answers a on a.id = at.answer_id
    group by 1
  ), class_comparison as (
    select coalesce(at.resolved_classroom_id, 0) classroom_id, coalesce(c.name, 'Sin clase') classroom_name,
      count(*)::integer attempts, count(*) filter (where at.is_correct)::integer correct,
      round(100.0 * count(*) filter (where not at.is_correct) / nullif(count(*), 0), 1) failure_percent,
      round(avg(at.time_taken_seconds) filter (where at.time_taken_seconds is not null), 1) average_time_seconds
    from attempts at left join public.classrooms c on c.id = at.resolved_classroom_id group by 1, 2
  ), temporal as (
    select date_trunc('day', attempted_at)::date as "day", count(*)::integer attempts,
      round(100.0 * count(*) filter (where not is_correct) / nullif(count(*), 0), 1) failure_percent,
      round(avg(time_taken_seconds) filter (where time_taken_seconds is not null), 1) average_time_seconds
    from attempts where attempted_at >= now() - interval '30 days' group by 1 order by 1
  ), subject_student_scores as (
    select ah.student_id, avg(case when ah.is_correct then 1.0 else 0.0 end) subject_accuracy
    from public.attempt_history ah join public.questions q on q.id = ah.question_id
    where q.subject_id = v_subject_id group by ah.student_id
  ), ranked as (
    select student_id, subject_accuracy, percent_rank() over(order by subject_accuracy) pr from subject_student_scores
  ), discrimination as (
    select round(
      (avg(case when a.is_correct then 1.0 else 0.0 end) filter (where r.pr >= 0.73)
       - avg(case when a.is_correct then 1.0 else 0.0 end) filter (where r.pr <= 0.27))::numeric, 3
    ) value
    from attempts a join ranked r on r.student_id = a.student_id
  ), recent as (
    select
      round(100.0 * count(*) filter (where not is_correct and attempted_at >= now() - interval '7 days') / nullif(count(*) filter (where attempted_at >= now() - interval '7 days'), 0), 1) current_failure,
      round(100.0 * count(*) filter (where not is_correct and attempted_at >= now() - interval '14 days' and attempted_at < now() - interval '7 days') / nullif(count(*) filter (where attempted_at >= now() - interval '14 days' and attempted_at < now() - interval '7 days'), 0), 1) previous_failure
    from attempts
  )
  select jsonb_build_object(
    'question', (select jsonb_build_object('id', q.id, 'text', q.text, 'type', q.type, 'subjectId', q.subject_id, 'classroomId', q.classroom_id, 'topicId', q.topic_id, 'explanation', q.explanation, 'mediaType', q.media_type, 'mediaPath', q.media_path, 'mediaAltText', q.media_alt_text, 'mediaCaption', q.media_caption, 'pointsBase', q.points_base, 'timeLimitSeconds', q.time_limit_seconds, 'difficulty', q.difficulty, 'active', q.active, 'subjectName', s.name, 'classroomName', c.name, 'topicName', st.title) from public.questions q join public.subjects s on s.id = q.subject_id left join public.classrooms c on c.id = q.classroom_id left join public.subject_topics st on st.id = q.topic_id where q.id = p_question_id),
    'summary', (select jsonb_build_object('totalAttempts', coalesce(total_attempts,0), 'correctAttempts', coalesce(correct_attempts,0), 'failedAttempts', coalesce(failed_attempts,0), 'sampleSize', coalesce(sample_size,0), 'lowSample', coalesce(sample_size,0) < 10, 'abandonmentPercent', coalesce(abandonment_percent,0), 'averageTimeSeconds', average_time_seconds, 'discrimination', (select value from discrimination), 'failureTrendPoints', coalesce((select current_failure - previous_failure from recent),0)) from summary),
    'answerDistribution', coalesce((select jsonb_agg(jsonb_build_object('label', label, 'count', count, 'correct', correct, 'percent', round(100.0 * count / nullif((select total_attempts from summary),0),1)) order by count desc) from answer_distribution), '[]'::jsonb),
    'classComparison', coalesce((select jsonb_agg(to_jsonb(class_comparison) order by failure_percent desc) from class_comparison), '[]'::jsonb),
    'temporalTrend', coalesce((select jsonb_agg(to_jsonb(temporal) order by temporal."day") from temporal), '[]'::jsonb),
    'classOptions', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name) order by c.name) from public.classrooms c where c.subject_id = v_subject_id and c.active), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;

create or replace function public.get_teacher_question_affected_students_page(
  p_question_id bigint, p_classroom_id bigint default null, p_date_from timestamptz default null, p_date_to timestamptz default null, p_limit integer default 20, p_offset integer default 0
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user_id uuid := auth.uid(); v_limit integer := least(greatest(coalesce(p_limit,20),1),100); v_offset integer := greatest(coalesce(p_offset,0),0); v_result jsonb;
begin
  if not exists (select 1 from public.questions q join public.subjects s on s.id = q.subject_id where q.id = p_question_id and (public.is_admin() or s.teacher_id = v_user_id)) then raise exception 'Question report access denied'; end if;
  with attempts as (
    select ah.*, coalesce(ga.classroom_id, q.classroom_id) resolved_classroom_id
    from public.attempt_history ah join public.questions q on q.id = ah.question_id left join public.game_attempts ga on ga.id = ah.attempt_id
    where ah.question_id = p_question_id and not ah.is_correct
      and (p_classroom_id is null or coalesce(ga.classroom_id, q.classroom_id) = p_classroom_id)
      and (p_date_from is null or ah.attempted_at >= p_date_from) and (p_date_to is null or ah.attempted_at < p_date_to)
  ), grouped as (
    select a.student_id, coalesce(p.alias, 'Alumno') alias, count(*)::integer failures,
      count(*)::integer attempts, round(avg(a.time_taken_seconds) filter(where a.time_taken_seconds is not null),1) average_time_seconds,
      max(a.attempted_at) last_attempt_at, coalesce(max(c.name), 'Sin clase') classroom_name
    from attempts a left join public.profiles p on p.id = a.student_id left join public.classrooms c on c.id = a.resolved_classroom_id
    group by a.student_id, p.alias
  ), page as (select * from grouped order by failures desc, last_attempt_at desc nulls last limit v_limit offset v_offset)
  select jsonb_build_object('items', coalesce((select jsonb_agg(to_jsonb(page) order by failures desc, last_attempt_at desc nulls last) from page), '[]'::jsonb), 'total', (select count(*) from grouped)) into v_result;
  return v_result;
end;
$$;

